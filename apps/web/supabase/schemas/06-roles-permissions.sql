/*
 * -------------------------------------------------------
 * Sección: Permisos de los roles
 * Asocia cada rol de equipo con los permisos de `app_permissions` que tiene
 * (por ejemplo, `owner` tiene `roles.manage`). Las políticas RLS y la
 * aplicación preguntan por permisos, no por roles, con `has_permission`; así
 * se pueden crear roles nuevos sin tocar ninguna política.
 * -------------------------------------------------------
 */
-- Tabla de permisos por rol.
create table if not exists
  public.role_permissions (
    id bigint generated by default as identity primary key,
    role varchar(50) references public.roles (name) not null,
    permission public.app_permissions not null,
    unique (role, permission)
  );

comment on table public.role_permissions is 'The permissions for a role';

comment on column public.role_permissions.role is 'The role the permission is for';

comment on column public.role_permissions.permission is 'The permission for the role';

-- Índice para resolver rápidamente los permisos de un rol.
create index ix_role_permissions_role on public.role_permissions (role);

-- Se retiran todos los permisos para concederlos después de forma explícita.
revoke all on public.role_permissions
from
  anon,
  authenticated,
  service_role;

-- Solo service_role (migraciones, semillas y herramientas de administración)
-- puede modificar la asignación de permisos.
grant
select
,
  insert,
update,
delete on table public.role_permissions to service_role;

-- Los usuarios autenticados solo la leen.
grant
select
  on table public.role_permissions to authenticated;

-- Función `public.has_permission`: indica si un usuario tiene un permiso en una
-- cuenta a través del rol de su membresía. Es la función que usan las
-- políticas RLS de las tablas de negocio (facturación, invitaciones...).
create
or replace function public.has_permission (
  user_id uuid,
  account_id uuid,
  permission_name public.app_permissions
) returns boolean
set
  search_path = '' as $$
begin
    return exists(
        select
            1
        from
            public.accounts_memberships
	    join public.role_permissions on
		accounts_memberships.account_role =
		role_permissions.role
        where
            accounts_memberships.user_id = has_permission.user_id
            and accounts_memberships.account_id = has_permission.account_id
            and role_permissions.permission = has_permission.permission_name);

end;

$$ language plpgsql;

grant
execute on function public.has_permission (uuid, uuid, public.app_permissions) to authenticated,
service_role;

-- Función `public.has_more_elevated_role`: indica si el usuario tiene un rol de
-- jerarquía estrictamente superior a `role_name` en la cuenta (el propietario
-- principal siempre la tiene). Se usa, por ejemplo, para impedir que alguien
-- invite o asigne un rol superior al suyo.
create
or replace function public.has_more_elevated_role (
  target_user_id uuid,
  target_account_id uuid,
  role_name varchar
) returns boolean
set
  search_path = '' as $$
declare
    declare is_primary_owner boolean;
    user_role_hierarchy_level int;
    target_role_hierarchy_level int;
begin
    -- Check if the user is the primary owner of the account
    select
        exists (
            select
                1
            from
                public.accounts
            where
                id = target_account_id
                and primary_owner_user_id = target_user_id) into is_primary_owner;

    -- If the user is the primary owner, they have the highest role and can
    --   perform any action
    if is_primary_owner then
        return true;
    end if;

    -- Get the hierarchy level of the user's role within the account
    select
        hierarchy_level into user_role_hierarchy_level
    from
        public.roles
    where
        name =(
            select
                account_role
            from
                public.accounts_memberships
            where
                account_id = target_account_id
                and target_user_id = user_id);

    if user_role_hierarchy_level is null then
        return false;
    end if;

    -- Get the hierarchy level of the target role
    select
        hierarchy_level into target_role_hierarchy_level
    from
        public.roles
    where
        name = role_name;

    -- If the target role does not exist, the user cannot perform the action
    if target_role_hierarchy_level is null then
        return false;
    end if;

    -- If the user's role is higher than the target role, they can perform
    --   the action
    return user_role_hierarchy_level < target_role_hierarchy_level;

end;

$$ language plpgsql;

grant
execute on function public.has_more_elevated_role (uuid, uuid, varchar) to authenticated,
service_role;

-- Función `public.has_same_role_hierarchy_level`: indica si el rol del usuario
-- tiene la misma jerarquía que `role_name` (el propietario principal siempre
-- cumple). Complementa a la anterior en las reglas de invitación.
create
or replace function public.has_same_role_hierarchy_level (
  target_user_id uuid,
  target_account_id uuid,
  role_name varchar
) returns boolean
set
  search_path = '' as $$
declare
    is_primary_owner boolean;
    user_role_hierarchy_level int;
    target_role_hierarchy_level int;
begin
    -- Check if the user is the primary owner of the account
    select
        exists (
            select
                1
            from
                public.accounts
            where
                id = target_account_id
                and primary_owner_user_id = target_user_id) into is_primary_owner;

    -- If the user is the primary owner, they have the highest role and can perform any action
    if is_primary_owner then
        return true;
    end if;

    -- Get the hierarchy level of the user's role within the account
    select
        hierarchy_level into user_role_hierarchy_level
    from
        public.roles
    where
        name =(
            select
                account_role
            from
                public.accounts_memberships
            where
                account_id = target_account_id
                and target_user_id = user_id);

    -- If the user does not have a role in the account, they cannot perform the action
    if user_role_hierarchy_level is null then
        return false;
    end if;

    -- Get the hierarchy level of the target role
    select
        hierarchy_level into target_role_hierarchy_level
    from
        public.roles
    where
        name = role_name;

    -- If the target role does not exist, the user cannot perform the action
    if target_role_hierarchy_level is null then
        return false;
    end if;

   -- check the user's role hierarchy level is the same as the target role
    return user_role_hierarchy_level = target_role_hierarchy_level;

end;

$$ language plpgsql;

grant
execute on function public.has_same_role_hierarchy_level (uuid, uuid, varchar) to authenticated,
service_role;

-- RLS activada sobre role_permissions.
alter table public.role_permissions enable row level security;

-- Política SELECT: los usuarios autenticados pueden leer la tabla completa,
-- porque es un catálogo global (qué permisos tiene cada rol) sin datos de
-- ningún tenant.
create policy role_permissions_read on public.role_permissions for
select
  to authenticated using (true);
